/* Atami treasure hunt — the playing field and its six areas
   From the committee's map:
   https://maps.app.goo.gl/Mkf8ULbmPrUoC4KS8

   Teams roam in whatever order they like, so there is no walking line
   here — an area is a patch of Atami you are in, not a stop you arrive
   at in turn.

   The six areas tile FIELD_BOUNDARY: they sit side by side with shared
   borders, cover the field completely, and never overlap. They were
   generated by splitting the boundary so that every point belongs to
   whichever of the six centres is nearest, which is what makes that
   true by construction rather than by careful drawing.

   Those centres are the numbered circles on the committee's drawn map,
   georeferenced against the five original checkpoint coordinates and
   accurate to about 6 m. The outer boundary is traced by eye from the
   same drawing, so it is the loosest part of this: treat it as "roughly
   this edge of town". Borders between areas fall halfway between two
   centres and so do not follow streets — if a border needs to sit on a
   particular road, hand-edit that shared edge in both areas that use
   it. [lat, lng] pairs. */

